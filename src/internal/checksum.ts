/** Check-digit algorithms. Inputs are already shape-checked by the caller. */

export function luhn(digits: string): boolean {
  let sum = 0;
  let double = false;
  for (let i = digits.length - 1; i >= 0; i--) {
    let d = digits.charCodeAt(i) - 48;
    if (d < 0 || d > 9) return false;
    if (double) {
      d *= 2;
      if (d > 9) d -= 9;
    }
    sum += d;
    double = !double;
  }
  return digits.length > 0 && sum % 10 === 0;
}

/** Letters expand to two digits (A=10 ... Z=35), then the number is reduced mod 97. */
export function mod97(s: string): number {
  let rem = 0;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c >= 48 && c <= 57) rem = (rem * 10 + (c - 48)) % 97;
    else if (c >= 65 && c <= 90) rem = (rem * 100 + (c - 55)) % 97;
    else return -1;
  }
  return rem;
}

