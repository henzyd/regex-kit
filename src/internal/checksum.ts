export function verhoeff(digits: string): boolean {
  let c = 0;
  for (let i = 0; i < digits.length; i++) {
    const d = digits.charCodeAt(digits.length - 1 - i) - 48;
    if (d < 0 || d > 9) return false;
    c = D[c]![P[i % 8]![d]!]!;
  }
  return c === 0;
}

/** Weighted sum of digits modulo `mod`. */
export function weighted(digits: string, weights: readonly number[]): number {
  let sum = 0;
  for (let i = 0; i < weights.length; i++) sum += (digits.charCodeAt(i) - 48) * weights[i]!;
  return sum;
}

/** GS1 mod-10 check digit used by EAN, UPC and GTIN. The last digit is the check digit. */
export function gs1(digits: string): boolean {
  let sum = 0;
  const n = digits.length;
  for (let i = 0; i < n - 1; i++) {
    const d = digits.charCodeAt(n - 2 - i) - 48;
    sum += d * (i % 2 === 0 ? 3 : 1);
  }
  return (10 - (sum % 10)) % 10 === digits.charCodeAt(n - 1) - 48;
}
